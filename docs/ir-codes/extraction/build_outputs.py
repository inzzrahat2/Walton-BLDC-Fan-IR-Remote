"""Turn extracted command definitions into IR code files.

Usage: python3 -I build_outputs.py <commands.json> <out_dir>
Reproduces the app's encoders (r.Ij.n / r.Ij.d) for commands that have no stored raw timing.
"""
import json
import os
import sys

commands_path, out_dir = sys.argv[1:3]
os.makedirs(out_dir, exist_ok=True)
CARRIER = 38_000
FRAME_PERIOD_US = 108_000
REPEAT_FRAME = [8880, 2230, 580]

# Table -> brand, as selected in the app (r.Oo.a and r.so.f).
TABLES = {
    ("r.Kb.<clinit>:()V", 0): ("Atomberg", "brand string match"),
    ("r.Kb.<clinit>:()V", 1): ("Activa", "inferred: fallback list; Activa is the only brand without its own table"),
    ("r.Kb.<clinit>:()V", 2): ("Orient", "brand string match"),
    ("r.wx.<clinit>:()V", 0): ("Walton", "remote body captioned WALTON"),
    ("r.if.<clinit>:()V", 0): ("Innoel", "remote body captioned INNOEL"),
}
KB_SPLITS = [10, 26]  # Kb.a = first 10, Kb.b = next 16, Kb.c = rest


def app_encode(command):
    """r.Ij.n: NEC frame with the fixed address bytes D8 7E."""
    pattern = [8880, 4470]
    for byte in (0xD8, 0x7E, command, command ^ 0xFF):
        for bit in range(8):
            pattern += [580, 1620 if byte >> bit & 1 else 620]
    return pattern + [580]


def with_repeats(frame, count):
    """r.Ij.d: frame followed by `count` NEC repeat frames on a 108 ms period."""
    out, prev = list(frame), frame
    for _ in range(count):
        out.append(FRAME_PERIOD_US - sum(prev))
        out += REPEAT_FRAME
        prev = REPEAT_FRAME
    return out


def decode_nec(raw):
    bits = [1 if raw[i + 1] > 1000 else 0 for i in range(2, 66, 2)]
    return [sum(bits[j * 8 + k] << k for k in range(8)) for j in range(4)]


def pronto(raw):
    """Pronto hex of one frame, padded with the inter-frame gap."""
    frame = raw[:67]
    pairs = frame + [FRAME_PERIOD_US - sum(frame)]
    words = [0x0000, round(1_000_000 / (CARRIER * 0.241246)), len(pairs) // 2, 0]
    words += [max(1, round(us * CARRIER / 1_000_000)) for us in pairs]
    return " ".join(f"{w:04X}" for w in words)


cmds = json.load(open(commands_path))
groups = {}
kb_index = 0
for c in cmds:
    if c["method"].startswith("r.Kb"):
        table = 0 if kb_index < KB_SPLITS[0] else 1 if kb_index < KB_SPLITS[1] else 2
        kb_index += 1
        key = (c["method"], table)
    else:
        key = (c["method"], 0)
    groups.setdefault(key, []).append(c)

out = []
for key, items in groups.items():
    brand, source = TABLES[key]
    buttons = []
    seen_codes = {}
    for c in items:
        name = c["label"] or c["id"]
        notes = []
        if c["raw"]:
            frame, origin = c["raw"], "stored raw timing"
        else:
            frame, origin = app_encode(c["code"]), "generated by app encoder (address D8 7E)"
        addr0, addr1, cmd, inv = decode_nec(frame)
        assert cmd == c["code"] and cmd ^ inv == 0xFF, (brand, name)
        if not c["raw"] and brand == "Activa":
            notes.append("app has no stored signal; it falls back to address D8 7E, which differs from this remote (00) - likely an app bug, probably won't work")
        twins = [o["label"] or o["id"] for o in items if o is not c and o["code"] == c["code"] and not o["raw"]]
        if twins and not c["raw"]:
            notes.append(f"same code as '{twins[0]}' - looks like an unfinished placeholder in the app; probably not the real signal")
        transmit = with_repeats(frame, c["e"]) if c["e"] else frame
        if c["e"]:
            notes.append(f"sent as a long press: frame + {c['e']} NEC repeat frames")
        if c["repeat"]:
            notes.append("app keeps sending NEC repeat frames every 108 ms while held")
        standard = addr0 ^ addr1 == 0xFF
        buttons.append({
            "button": name,
            "protocol": "NEC" if standard else "NECext",
            "address": f"{addr0:02X}" if standard else f"{addr0:02X} {addr1:02X}",
            "command": f"{cmd:02X}",
            "nec_bytes": f"{addr0:02X} {addr1:02X} {cmd:02X} {inv:02X}",
            "nec32_lsb_first": f"0x{(inv << 24) | (cmd << 16) | (addr1 << 8) | addr0:08X}",
            "carrier_hz": CARRIER,
            "pattern_us": transmit,
            "pronto": pronto(frame),
            "source": origin,
            "notes": notes,
        })
    out.append({"brand": brand, "brand_source": source, "buttons": buttons})

json.dump(out, open(os.path.join(out_dir, "fan_ir_codes.json"), "w"), indent=1)

with open(os.path.join(out_dir, "fan_ir_codes.ir"), "w") as f:
    f.write("Filetype: IR signals file\nVersion: 1\n")
    for g in out:
        for b in g["buttons"]:
            a = b["address"].split()
            f.write(f"#\nname: {g['brand']}_{b['button'].replace(' ', '_')}\ntype: parsed\n")
            f.write(f"protocol: {b['protocol']}\naddress: {a[0]} {a[1] if len(a) > 1 else '00'} 00 00\n")
            f.write(f"command: {b['command']} 00 00 00\n")

with open(os.path.join(out_dir, "fan_ir_codes.md"), "w") as f:
    f.write("# BLDC fan IR codes (extracted from REMOTE_BLDC_FAN v14.0)\n\n")
    f.write("All codes: NEC, 38 kHz carrier, LSB first. Full timing arrays and Pronto hex are in fan_ir_codes.json; "
            "a Flipper Zero file is fan_ir_codes.ir.\n\n")
    for g in out:
        f.write(f"## {g['brand']}\n\n_Table identified by: {g['brand_source']}._\n\n")
        f.write("| Button | Protocol | Address | Command | NEC bytes | Notes |\n|---|---|---|---|---|---|\n")
        for b in g["buttons"]:
            f.write(f"| {b['button']} | {b['protocol']} | {b['address']} | {b['command']} | `{b['nec_bytes']}` | {'; '.join(b['notes'])} |\n")
        f.write("\n")

print({g["brand"]: len(g["buttons"]) for g in out})
